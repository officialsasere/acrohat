describe('dynamic arrays', () => {
  it('spill into the cells below and to the right', () => {
    const s = sheet({ A1: '=SEQUENCE(3,2)' })
    expect([s.v('A1'), s.v('B1'), s.v('A2'), s.v('B2'), s.v('A3'), s.v('B3')]).toEqual([1, 2, 3, 4, 5, 6])
    expect(s.v('C1')).toBe(null)
  })
  it('are blocked by existing content, and recover when it goes away', () => {
    const s = sheet({ A2: 'in the way', A1: '=SEQUENCE(3)' })
    expect(isErr(s.v('A1')) && (s.v('A1') as { code: string }).code).toBe('#SPILL!')
    s.set('A2', '')
    expect([s.v('A1'), s.v('A2'), s.v('A3')]).toEqual([1, 2, 3])
  })
  it('can be read by other formulas, including after they change size', () => {
    const s = sheet({ A1: '=SEQUENCE(B1)', B1: '3', C1: '=SUM(A1:A10)', D1: '=SUM(A1#)' })
    expect(s.v('C1')).toBe(6)
    expect(s.v('D1')).toBe(6)
    s.set('B1', '5')
    expect(s.v('C1')).toBe(15)
    expect(s.v('D1')).toBe(15)
    s.set('B1', '2')
    expect(s.v('C1')).toBe(3)
    expect(s.v('A4')).toBe(null)
  })
  it('SORT, UNIQUE, FILTER, TRANSPOSE and friends', () => {
    const d = { A1: '3', A2: '1', A3: '2', A4: '1', B1: 'c', B2: 'a', B3: 'b', B4: 'a' }
    const s = sheet({ ...d, D1: '=SORT(A1:A4)', E1: '=UNIQUE(A1:A4)', F1: '=FILTER(B1:B4,A1:A4>1)', G1: '=TRANSPOSE(A1:A3)', H6: '=SORTBY(B1:B4,A1:A4,-1)' })
    expect([s.v('D1'), s.v('D2'), s.v('D3'), s.v('D4')]).toEqual([1, 1, 2, 3])
    expect([s.v('E1'), s.v('E2'), s.v('E3')]).toEqual([3, 1, 2])
    expect([s.v('F1'), s.v('F2')]).toEqual(['c', 'b'])
    expect([s.v('G1'), s.v('H1'), s.v('I1')]).toEqual([3, 1, 2])
    expect([s.v('H6'), s.v('H7'), s.v('H8'), s.v('H9')]).toEqual(['c', 'b', 'a', 'a'])
  })
  it('arithmetic works on whole ranges', () => {
    const s = sheet({ A1: '1', A2: '2', A3: '3', B1: '=A1:A3*10', C1: '=IF(A1:A3>1,"big","small")', D1: '=SUM(A1:A3*A1:A3)' })
    expect([s.v('B1'), s.v('B2'), s.v('B3')]).toEqual([10, 20, 30])
    expect([s.v('C1'), s.v('C2'), s.v('C3')]).toEqual(['small', 'big', 'big'])
    expect(s.v('D1')).toBe(14)
  })
  it('VSTACK, HSTACK, TAKE, DROP, TOCOL, SEQUENCE dates', () => {
    const s = sheet({ A1: '=VSTACK({1,2},{3,4})', D1: '=HSTACK({1;2},{3;4})', G1: '=TAKE({1,2,3,4},1,2)', I1: '=TOCOL({1,2;3,4})' })
    expect([s.v('A1'), s.v('B2'), s.v('D2'), s.v('E1'), s.v('G1'), s.v('H1'), s.v('I4')]).toEqual([1, 4, 2, 3, 1, 2, 4])
  })
})

