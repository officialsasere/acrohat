function sheet(cells: Record<string, string> = {}) {
  const b = new Book()
  const id = b.wb.sheets[0].id
  const addr = (a: string) => parseA1(a)!
  const set = (a: string, t: string) => { const p = addr(a); b.setInput(id, p.row, p.col, t) }
  const v = (a: string): Scalar => { const p = addr(a); return b.value(id, p.row, p.col) }
  const show = (a: string) => { const p = addr(a); return b.display(id, p.row, p.col).text }
  for (const [a, t] of Object.entries(cells)) set(a, t)
  return { b, id, set, v, show }
}
const calc = (formula: string, cells: Record<string, string> = {}): Scalar => {
  const s = sheet(cells)
  s.set('Z99', formula.startsWith('=') ? formula : '=' + formula)
  return s.v('Z99')
}
const num = (f: string, cells?: Record<string, string>) => { const r = calc(f, cells); if (typeof r !== 'number') throw new Error(`${f} gave ${String(r)}`); return r }
const err = (f: string, cells?: Record<string, string>) => { const r = calc(f, cells); return isErr(r) ? r.code : String(r) }

