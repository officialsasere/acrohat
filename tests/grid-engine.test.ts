describe('references and recalculation', () => {
  it('updates dependents when a cell changes', () => {
    const s = sheet({ A1: '2', A2: '3', A3: '=A1*A2', A4: '=A3+1' })
    expect(s.v('A4')).toBe(7)
    s.set('A1', '10')
    expect(s.v('A3')).toBe(30)
    expect(s.v('A4')).toBe(31)
  })
  it('handles ranges, absolute references and cross-sheet references', () => {
    const s = sheet({ A1: '1', A2: '2', A3: '3', B1: '=SUM($A$1:$A$3)' })
    expect(s.v('B1')).toBe(6)
    const b2 = s.b.addSheet('Data')
    s.b.setInput(b2.id, 0, 0, '100')
    s.set('C1', '=Data!A1+1')
    expect(s.v('C1')).toBe(101)
    s.b.setInput(b2.id, 0, 0, '200')
    expect(s.v('C1')).toBe(201)
    s.set('C2', "='Data'!A1*2")
    expect(s.v('C2')).toBe(400)
  })
  it('keeps references right when a sheet is renamed', () => {
    const s = sheet({ A1: '5' })
    const d = s.b.addSheet('Data')
    s.b.setInput(d.id, 0, 0, '=Sheet1!A1*2')
    expect(s.b.value(d.id, 0, 0)).toBe(10)
    s.b.renameSheet(s.id, 'Numbers')
    expect(s.b.getCell(d.id, 0, 0)?.f).toBe('=Numbers!A1*2')
    s.set('A1', '7')
    expect(s.b.value(d.id, 0, 0)).toBe(14)
  })
  it('finds circular references instead of hanging', () => {
    const s = sheet({ A1: '=B1', B1: '=A1' })
    expect(isErr(s.v('A1'))).toBe(true)
    s.set('B1', '3')
    expect(s.v('A1')).toBe(3)
  })
  it('copes with very long chains', () => {
    const s = sheet({ A1: '1' })
    s.b.load(() => { for (let i = 2; i <= 6000; i++) s.b.setInput(s.id, i - 1, 0, `=A${i - 1}+1`) })
    expect(s.v('A6000')).toBe(6000)
    s.set('A1', '10')
    expect(s.v('A6000')).toBe(6009)
  })
  it('whole-column references', () => {
    const s = sheet({ A1: '1', A2: '2', A50: '10', B1: '=SUM(A:A)', B2: '=COUNT(A:A)' })
    expect(s.v('B1')).toBe(13)
    expect(s.v('B2')).toBe(3)
  })
  it('defined names', () => {
    const s = sheet({ A1: '10', A2: '20' })
    s.b.wb.names.push({ name: 'Prices', ref: 'Sheet1!$A$1:$A$2' }, { name: 'Tax', ref: '0.2' })
    s.set('B1', '=SUM(Prices)*(1+Tax)')
    expect(s.v('B1')).toBe(36)
    s.set('A1', '20')
    expect(s.v('B1')).toBe(48)
  })
})

